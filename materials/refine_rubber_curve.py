        y_fix = y_prev + (y_next - y_prev) * (x - x_prev) / (x_next - x_prev)
        original[i] = (x, y_fix)
        print(f"Fixed duplicate stress: ({x:.6f}, {y:.6f}) -> ({x:.6f}, {y_fix:.9f})")
