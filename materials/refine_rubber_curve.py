def log_interp(x1, y1, x2, y2, x):
    """두 점 사이 log-stress 보간 (둘 다 음수인 경우)"""
    if y1 < 0 and y2 < 0 and abs(y1) > 1e-6 and abs(y2) > 1e-6:
        log1, log2 = math.log(abs(y1)), math.log(abs(y2))
        t = (x - x1) / (x2 - x1)
        y = -math.exp(log1 + t * (log2 - log1))
    else:
        t = (x - x1) / (x2 - x1)
        y = y1 + t * (y2 - y1)
    return y

def slope(p1, p2):
    dx = p2[0] - p1[0]
    return (p2[1] - p1[1]) / dx if abs(dx) > 1e-15 else 0.0

def refine(pts, abs_stress_threshold=3.0, passes=2):
    """
    선형 보간 오차가 큰 구간에 log-midpoint 추가.
    기준: |stress| > abs_stress_threshold MPa인 인접 쌍마다
    log-stress 중간점 삽입 (선형 보간 오차를 지수적으로 감소시킴).
    passes: 반복 횟수 (한 번에 절반으로 줄어듦)
    """
    pts = list(pts)
    for _ in range(passes):
        result = [pts[0]]
        for i in range(len(pts) - 1):
            x1, y1 = pts[i]
            x2, y2 = pts[i+1]
            # 두 점 모두 |stress| > threshold 이면 중간점 삽입
            if abs(y1) > abs_stress_threshold and abs(y2) > abs_stress_threshold:
                xm = (x1 + x2) / 2.0
                ym = log_interp(x1, y1, x2, y2, xm)
                # 선형 보간값과 비교해서 오차가 클 때만 추가
                ym_linear = (y1 + y2) / 2.0
                if abs(ym - ym_linear) > 0.5:  # 0.5 MPa 이상 차이
                    result.append((xm, ym))
            result.append((x2, y2))
        pts = result
    return pts

